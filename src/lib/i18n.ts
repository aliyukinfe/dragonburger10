export function t(lang: Lang, key: string): string {
  const keys = key.split('.')
  let val: any = translations[lang]
  for (const k of keys) {
    val = val?.[k]
    if (val === undefined) {
      val = (translations.en as any)
      for (const k2 of keys) val = val?.[k2]
      break
    }
  }
  return typeof val === 'string' ? val : key
}
